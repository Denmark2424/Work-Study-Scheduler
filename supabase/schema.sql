-- 1. GRANT SCHEMA ACCESS
grant usage on schema public to anon, authenticated;

-- 2. PROFILES TABLE (Stores user profile metadata)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  name text not null,
  username text unique not null,
  email text,
  plan text default 'free' check (plan in ('free', 'student')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable Row Level Security (RLS) on profiles
alter table public.profiles enable row level security;

-- Drop existing policies if re-running
drop policy if exists "Users can read their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can insert their own profile" on public.profiles;
drop policy if exists "Allow lookup of usernames for login" on public.profiles;

-- Policies for profiles
create policy "Allow lookup of usernames for login"
  on public.profiles for select
  using (true);

create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = id);

create policy "Users can insert their own profile"
  on public.profiles for insert
  with check (auth.uid() = id);


-- 3. SCHEDULES TABLE (Stores grid cells for each user)
create table if not exists public.schedules (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references auth.users on delete cascade not null,
  day text not null check (day in ('MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN')),
  slot text not null,
  type text not null check (type in ('class', 'work', 'study', 'free')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint unique_user_day_slot unique (user_id, day, slot)
);

-- Enable RLS on schedules
alter table public.schedules enable row level security;

drop policy if exists "Users can manage their own schedule" on public.schedules;
create policy "Users can manage their own schedule"
  on public.schedules for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);


-- 4. DEADLINES TABLE (Stores user deadlines and tasks)
create table if not exists public.deadlines (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null,
  title text not null,
  subject text default '',
  day text not null check (day in ('MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN')),
  time text not null,
  urgent boolean default false not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable RLS on deadlines
alter table public.deadlines enable row level security;

drop policy if exists "Users can manage their own deadlines" on public.deadlines;
create policy "Users can manage their own deadlines"
  on public.deadlines for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);


-- 5. AUTOMATIC PROFILE CREATION TRIGGER
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, name, username, email, plan)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)),
    new.email,
    coalesce(new.raw_user_meta_data->>'plan', 'free')
  )
  on conflict (id) do update set
    name = coalesce(excluded.name, profiles.name),
    username = coalesce(excluded.username, profiles.username),
    plan = coalesce(excluded.plan, profiles.plan),
    updated_at = timezone('utc'::text, now());
  return new;
end;
$$ language plpgsql security definer;

-- Trigger definition
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();


-- 6. GRANT TABLE PRIVILEGES TO ROLES (Crucial for Postgres / Supabase)
grant all on all tables in schema public to anon, authenticated, service_role;
grant all on all sequences in schema public to anon, authenticated, service_role;
grant all on all routines in schema public to anon, authenticated, service_role;

alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant all on routines to anon, authenticated, service_role;
